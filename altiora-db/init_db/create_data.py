import csv
import json
import os
import random
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path

import bcrypt
from faker import Faker

OUTPUT_DIR = Path("../init_data")
OUTPUT_DIR.mkdir(exist_ok=True)

with open("map_data.json", encoding="utf-8") as f:
    DATA = json.load(f)

fake = Faker("es_MX") # save data in spanish

user_agency_list = []
user_buyer_list = []
properties_list = []
requests_list = []
reviews_list = []


# ── Helpers ───────────────────────────────────────────────────────────────────
def rand_date(days_back: int) -> datetime:
    """Fecha aleatoria dentro de los últimos N días, con zona horaria en centro america (UTC-6)."""
    delta = random.randint(0, days_back)
    # Zona horaria de Centro América (UTC-6)
    ca_tz = timezone(timedelta(hours=-6))
    return datetime.now(ca_tz) - timedelta(days=delta)

def rand_location() -> dict:
    """Returns a dict with province, city y district."""
    return random.choice(DATA["cr_locations"])

def rand_property_type() -> str:
    """Returns a random type of property based on weights/relevance define for the type of property."""
    types   = list(DATA["property_weights"].keys())
    weights = list(DATA["property_weights"].values())
    return random.choices(types, weights=weights, k=1)[0]

def rand_coords(province: str) -> tuple:
    """Aproximated coordinates for Costa Rica provinces."""
    coords = {
        "San José":   (9.93,  -84.08, 0.15),
        "Alajuela":   (10.02, -84.21, 0.20),
        "Heredia":    (10.00, -84.12, 0.15),
        "Cartago":    (9.86,  -83.92, 0.15),
        "Guanacaste": (10.33, -85.55, 0.40),
        "Puntarenas": (9.98,  -84.83, 0.50),
        "Limón":      (9.99,  -83.03, 0.30),
    }
    base_lat, base_lng, spread = coords.get(province, (9.93, -84.08, 0.2))
    lat = round(base_lat + random.uniform(-spread, spread), 7)
    lng = round(base_lng + random.uniform(-spread, spread), 7)
    return lat, lng

def build_property_title(ptype: str, location: dict, area: float, beds: int, floor: int) -> str:
    template = random.choice(DATA["property_title_templates"][ptype])
    return template.format(
        city     = location["city"],
        district = location["district"],
        province = location["province"],
        beds     = beds or random.randint(1, 5),
        floor    = floor or random.randint(2, 20),
        area     = area,
        unit     = f"{random.choice('ABCD')}-{random.randint(101, 420)}",
        name     = random.choice(DATA["condo_names"]),
    )

def image_urls(seed: str, count: int = 5) -> list[dict]:
    """Generate consistent picsum URLs for a property."""
    return [
        {"url": f"https://picsum.photos/seed/{seed}-{i}/1200/800", "order": i}
        for i in range(count)
    ]

def write_csv(name, fields, rows):
    path = OUTPUT_DIR / name
    file_exists = os.path.exists(path)
    with open(path, "a", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        if not file_exists:
            w.writeheader()
        w.writerows(rows)
    print(f"  ✓ {name:38s} {len(rows):>4} filas")

def clean_output_dir():
    for old in OUTPUT_DIR.glob("*.csv"):
        old.unlink()


