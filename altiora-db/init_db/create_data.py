def seed_agencies():
    """Inserts records of agencies in csvs for user and profile data."""
    print("  → Seeding agencies...")
    agencies = DATA["agency_names"]

    rows_user_agency = []
    rows_agency_profile = []
    for i, agency in enumerate(agencies):
        user_id = str(uuid.uuid4())
        name = agency["name"]
        email = f"{name.lower().replace(' ', '')}.ventas@gmail.com"
        password = bcrypt.hashpw(agency["password"].encode(), bcrypt.gensalt()).decode()
        loc = rand_location()
        created = rand_date(random.randrange(500,1000))

        user_agency_list.append({"id": user_id, "name": name, "email": email})

        rows_user_agency.append({
            "id": user_id,
            "email": email,
            "password": password,
            "role": "agency",
            "created_at": created,
            "updated_at": created,
        })

        # despite de id can be autogenerated, the agency user one is created for using it later
        rows_agency_profile.append({
            "user_id": user_id,
            "agency_name": name,
            "description": fake.paragraph(nb_sentences=2),
            "website_url": f"https://www.{name.lower().replace(' ', '')}.com",
            "phone": fake.numerify("2#######"), # show in frontend as 2###-####
            "email_contact": email,
            "country": "Costa Rica",
            "city": loc["city"],
            "address": fake.street_address(),
            "founded_year": random.randint(1990, 2020),
            "is_verified": i < 3,
            "created_at": created,
            "updated_at": created,
        })
    
    write_csv("users.csv", rows_user_agency[0].keys(), rows_user_agency)
    write_csv("agency_profiles.csv", rows_agency_profile[0].keys(), rows_agency_profile)


